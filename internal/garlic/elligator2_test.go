// Test vectors from Elligator2.java's commented-out main(): TEST1
// encodes (alternative=false and =true); TEST2 decodes. The public
// keys in the vectors are unreduced 32-byte LE values; Elligator2
// arithmetic works with them mod p (2^255-19).
var (
	vecPoint = []byte{
		0x33, 0x95, 0x19, 0x64, 0x00, 0x3c, 0x94, 0x08,
		0x78, 0x06, 0x3c, 0xcf, 0xd0, 0x34, 0x8a, 0xf4,
		0x21, 0x50, 0xca, 0x16, 0xd2, 0x64, 0x6f, 0x2c,
		0x58, 0x56, 0xe8, 0x33, 0x83, 0x77, 0xd8, 0x80,
	}
	// vecPoint mod p, little-endian.
	vecPointReduced = []byte{
		0x46, 0x95, 0x19, 0x64, 0x00, 0x3c, 0x94, 0x08,
		0x78, 0x06, 0x3c, 0xcf, 0xd0, 0x34, 0x8a, 0xf4,
		0x21, 0x50, 0xca, 0x16, 0xd2, 0x64, 0x6f, 0x2c,
		0x58, 0x56, 0xe8, 0x33, 0x83, 0x77, 0xd8, 0x00,
	}
	vecRepFalse = []byte{
		0x28, 0x20, 0xb6, 0xb2, 0x41, 0xe0, 0xf6, 0x8a,
		0x6c, 0x4a, 0x7f, 0xee, 0x3d, 0x97, 0x82, 0x28,
		0xef, 0x3a, 0xe4, 0x55, 0x33, 0xcd, 0x41, 0x0a,
		0xa9, 0x1a, 0x41, 0x53, 0x31, 0xd8, 0x61, 0x2d,
	}
	vecRepTrue = []byte{
		0x3c, 0xfb, 0x87, 0xc4, 0x6c, 0x0b, 0x45, 0x75,
		0xca, 0x81, 0x75, 0xe0, 0xed, 0x1c, 0x0a, 0xe9,
		0xda, 0xe7, 0x9d, 0xb7, 0x8d, 0xf8, 0x69, 0x97,
		0xc4, 0x84, 0x7b, 0x9f, 0x20, 0xb2, 0x77, 0x18,
	}
	vecRep2 = []byte{
		0xe7, 0x35, 0x07, 0xd3, 0x8b, 0xae, 0x63, 0x99,
		0x2b, 0x3f, 0x57, 0xaa, 0xc4, 0x8c, 0x0a, 0xbc,
		0x14, 0x50, 0x95, 0x89, 0x28, 0x84, 0x57, 0x99,
		0x5a, 0x2b, 0x4c, 0xa3, 0x49, 0x0a, 0xa2, 0x07,
	}
	vecPoint2 = []byte{
		0x1e, 0x8a, 0xff, 0xfe, 0xd6, 0xbf, 0x53, 0xfe,
		0x27, 0x1a, 0xd5, 0x72, 0x47, 0x32, 0x62, 0xde,
		0xd8, 0xfa, 0xec, 0x68, 0xe5, 0xe6, 0x7e, 0xf4,
		0x5e, 0xbb, 0x82, 0xee, 0xba, 0x52, 0x60, 0x4f,
	}
)

func TestElligator2Vector(t *testing.T) {
	// Both encode alternatives of the same point decode back to the
	// point (reduced mod p).
	if got := Elligator2Decode(vecRepFalse); !bytes.Equal(got, vecPointReduced) {
		t.Fatalf("decode(alt=false) = %x, want %x", got, vecPointReduced)
	}
	if got := Elligator2Decode(vecRepTrue); !bytes.Equal(got, vecPointReduced) {
		t.Fatalf("decode(alt=true) = %x, want %x", got, vecPointReduced)
	}
	if got := Elligator2Decode(vecRep2); !bytes.Equal(got, vecPoint2) {
		t.Fatalf("decode(vec2) = %x, want %x", got, vecPoint2)
	}
}

func TestElligator2RoundTrip(t *testing.T) {
	// Round trips work for real X25519 public keys (curve points),
	// not arbitrary byte strings. About half of all keys are
	// encodable; GenerateElligator2Keypair retries until it finds one.
	for i := 0; i < 20; i++ {
		_, pub, encoded, err := GenerateElligator2Keypair()
		if err != nil {
			t.Fatal(err)
		}
		got := Elligator2Decode(encoded)
		if got == nil {
			t.Fatal("decode of a generated encoding failed")
		}
		if !bytes.Equal(got, pub) {
			t.Fatalf("round trip mismatch:\n got %x\nwant %x", got, pub)
		}
	}
}

func TestElligator2UnreducedInput(t *testing.T) {
	// Encoding the raw TEST1 value (>= p) must behave like encoding
	// its reduction — both decode to the reduced point. The wire
	// format only ever encodes real public keys, but an unreduced
	// test vector must not crash.
	if got := Elligator2Decode(vecPoint); got == nil {
		t.Fatal("decode of raw point treated as representative failed")
	}
}
